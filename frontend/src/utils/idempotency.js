// Ключ идемпотентности для оформления чека и приёма оплаты.
//
// Ответ на «Оформить» мог потеряться (обрыв сети, таймаут), а кассир, не видя
// чека, нажимает кнопку ещё раз — и чек оформляется дважды, склад списывается
// дважды. Сервер умеет узнавать повтор по заголовку `Idempotency-Key`: тот же
// ключ — тот же результат, а не новая продажа.
//
// Правила:
//   * один ключ на одну «попытку» одной и той же корзины: повтор после
//     потерянного ответа или таймаута уходит с ТЕМ ЖЕ ключом;
//   * изменилась корзина (другая подпись запроса) — ключ новый;
//   * после успеха — новый;
//   * сервер ответил отказом (4xx) — попытка закончена, ключ новый: исправили
//     ввод, это уже другая попытка. Ключ остаётся только при обрыве/таймауте
//     и при 5xx — там неизвестно, дошло ли до сервера.
import { useMemo } from "react";

export function newKey() {
  try {
    if (globalThis.crypto?.randomUUID) return globalThis.crypto.randomUUID();
  } catch {
    /* падаем в запасной вариант */
  }
  const hex = (n) =>
    Array.from({ length: n }, () => Math.floor(Math.random() * 16).toString(16)).join("");
  return `${hex(8)}-${hex(4)}-4${hex(3)}-a${hex(3)}-${hex(12)}`;
}

export function useIdempotency() {
  return useMemo(() => {
    let cur = { sig: null, key: null };
    return {
      /** Ключ для запроса с данной подписью (обычно JSON тела). */
      keyFor(sig) {
        if (cur.sig !== sig) cur = { sig, key: newKey() };
        return cur.key;
      },
      /** Попытка закончилась — следующая начнёт с нового ключа. */
      done() {
        cur = { sig: null, key: null };
      },
      /** Разобрать ошибку: отказ сервера заканчивает попытку, обрыв — нет. */
      failed(e) {
        const status = e?.response?.status;
        if (status && status < 500) cur = { sig: null, key: null };
      },
    };
  }, []);
}
